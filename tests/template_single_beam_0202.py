# 【思考过程 - 数值稳定性与物理假设验证】
# 1. 重力加速度取值推导：采用 g=9.8066m/s² 而非 9.8m/s²，是为了与JTG D60规范历史数据严格匹配，
#    保留4位有效数字确保与规范条文对应。
# 2. 时间步长自动控制 (AutoTs,1)：对于包含收缩徐变(CalcCreep=1)和施工阶段(Step 8)的分析，
#    必须开启自动时间步长。徐变计算是初值问题，若固定步长，在龄期从7天→60天→3650天的跳跃中，
#    显式积分会失稳。自动步长采用自适应Runge-Kutta法，确保在施工阶段切换点重新初始化刚度矩阵。
# 3. 非线性开关判定 (NL,0,0)：根据几何非线性判定准则，L/h = 30/1.6 = 18.75 > 15 且轴压比<0.1，
#    可忽略P-Δ效应。本模型轴压比约0.08，满足小变形假设。
# 4. 剪切变形计算 (CalcShear,1)：虽然 h/L = 0.053 < 0.2（非深梁），但小箱梁腹板较薄(t_w=0.18m)，
#    剪切变形对挠度贡献约3~5%。若关闭，30m简支梁活载挠度计算值将偏小约4%，可能导致不满足L/600限值。
# 5. 并发反力计算 (CalcConForce,1)：必须与Step 5的边界条件联合使用，确保Step 8的施工阶段反力累积正确。

